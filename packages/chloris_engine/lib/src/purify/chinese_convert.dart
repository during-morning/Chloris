  /// 简体 → 繁体（未收录字保持原样）。
  static String s2t(String input) {
    if (input.isEmpty) return input;
    final b = StringBuffer();
    for (final r in input.runes) {
      final ch = String.fromCharCode(r);
      b.write(_s2t[ch] ?? ch);
    }
    return b.toString();
  }

